//! Wayland 专属能力。
//!
//! ## 限制说明
//!
//! Wayland 出于安全设计，**不提供**以下能力：
//! - 全局热键（仅可通过 XDG Desktop Portal，需用户授权）
//! - 窗口点击穿透
//! - 获取他人窗口句柄
//!
//! 这些限制源于协议本身，GTK / Qt / GPUI 均受同样约束。
//!
//! ## 可用方案
//!
//! | 能力 | 方案 |
//! |---|---|
//! | 全局快捷键 | XDG Portal（`org.freedesktop.portal.GlobalShortcuts`），非所有 DE 实现 |
//! | 会话探测 | `WAYLAND_DISPLAY` 环境变量 |
//!
//! ## 降级策略
//!
//! 不可实现的能力应**明确降级并在界面提示**，而非静默失败。
